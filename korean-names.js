    /**
     * 팀명을 한국어로 번역합니다. 번역이 없으면 원래 이름을 반환합니다.
     * @param {string} name - 영문 팀명
     * @returns {string} 한국어 팀명 또는 원래 팀명
     */
    translateTeam(name) {
        if (!name) return name;
        return this.teams[name] || name;
    },

